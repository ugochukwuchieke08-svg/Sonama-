const response = await fetch("https://fouanistore.com/nigeria-en/shop", {
  headers: { "User-Agent": "Mozilla/5.0" }
});

const html = await response.text();

const matches = [
  ...html.matchAll(/<a\b[^>]*href=["']([^"']*\/product\/1269[^"']*)["']/gi)
];

console.log("MATCHING PRODUCT LINKS:");

for (const match of matches) {
  console.log(match[1]);
}

if (!matches.length) {
  console.log("No matching anchor found. The product route may be generated by JavaScript.");
}
